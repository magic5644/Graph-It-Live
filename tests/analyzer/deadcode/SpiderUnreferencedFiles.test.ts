  "src/dead.ts": "export function a() { return 1; }\nexport const b = 2;\n",
  "src/script.ts": "console.log('side effect');\n",
  // reached only through a barrel; a barrel nothing imports, and its target
  "src/api/impl.ts": "export function fromBarrel() { return 1; }\n",
  "src/api/index.ts": "export * from './impl';\n",
