describe("scanUnreferencedFiles (#711)", { timeout: 60_000 }, () => {
  let root: string;
  let spider: Spider;
  let result: UnreferencedFilesScanResult;
  const listed = (): Map<string, UnreferencedFilesScanResult["unreferencedFiles"][number]> =>
    new Map(result.unreferencedFiles.map((file) => [file.relativePath, file]));

  beforeAll(async () => {
    root = await fs.mkdtemp(path.join(tmpdir(), "gitl-unreferenced-"));
    for (const [relative, content] of Object.entries(FILES)) {
      await fs.mkdir(path.dirname(path.join(root, relative)), { recursive: true });
      await fs.writeFile(path.join(root, relative), content);
    }
    spider = new SpiderBuilder().withRootDir(root).withReverseIndex(true).build();
    await spider.buildFullIndex();
    result = await scanUnreferencedFiles(spider, root, { verbose: true });
  });

  afterAll(async () => {
    await fs.rm(root, { recursive: true, force: true, maxRetries: 5, retryDelay: 100 });
  });

  it.each([
    ["src/dead.ts", 2, "low", ["no-importer"]],
    ["src/script.ts", 0, "low", ["no-importer"]],
    ["src/old/index.ts", 0, "low", ["no-importer"]],
    ["src/testOnly.ts", 1, "medium", ["test-only-use"]],
    ["src/plugins/csv.ts", 1, "low", ["no-importer", "dynamic-import-in-workspace"]],
    ["src/gen/client.ts", 1, "low", ["no-importer", "convention:generated"]],
    ["py/run.py", 0, "low", ["no-importer"]],
    ["lambda/fn.ts", 1, "low", ["no-importer", "named-in-deploy-manifest"]],
  ])("lists %s with %i export(s) at %s %j", (file, exports, confidence, reasons) => {
    expect(listed().get(file)).toMatchObject({ exports, confidence, reasons });
  });

  it("ignores the paths test files write: a fixture path does not keep a file alive", () => {
    expect(listed().has("src/dead.ts")).toBe(true);
  });

  it("names the tests to clean up with a file only tests import", () => {
    expect(listed().get("src/testOnly.ts")?.testImporters).toEqual(["tests/testOnly.test.ts"]);
    expect(listed().get("src/dead.ts")?.testImporters).toBeUndefined();
  });

  it("keeps files production code imports, directly or through a barrel", () => {
    for (const file of ["src/lazy.ts", "src/lib.ts", "src/api/impl.ts", "src/api/index.ts", "src/old/impl.ts", "src/both.ts", "py/mod.py"]) {
      expect(listed().has(file), file).toBe(false);
    }
  });

  it("lists the left-out files as excluded, each with its reason", () => {
    expect(result.excluded).toEqual(expect.arrayContaining([
      { relativePath: "src/main.ts", reason: "declared:package.json#main" },
      { relativePath: "src/worker.ts", reason: "named-in:build.mjs" },
      { relativePath: "src/Page.tsx", reason: "convention:framework-default-export" },
      { relativePath: "src/env.d.ts", reason: "convention:type-declaration" },
      { relativePath: "tests/testOnly.test.ts", reason: "convention:test-file" },
      { relativePath: "py/__init__.py", reason: "convention:package-init" },
      { relativePath: "pkg/dist-tsc/out.js", reason: "gitignored" },
      { relativePath: "vitest.config.ts", reason: "convention:config-file" },
      { relativePath: "pkg/index.generated.ts", reason: "gitignored" },
    ]));
    const excludedPaths = new Set(result.excluded?.map((item) => item.relativePath));
    expect(result.unreferencedFiles.filter((file) => excludedPaths.has(file.relativePath))).toEqual([]);
  });

  it("counts every file per confidence and sorts the list by path", () => {
    expect(result.byConfidence).toEqual({ high: 0, medium: 1, low: result.totalUnreferencedFiles - 1 });
    const paths = result.unreferencedFiles.map((file) => file.relativePath);
    expect(paths).toEqual([...paths].sort((a, b) => a.localeCompare(b)));
    expect(result).toMatchObject({ minConfidence: "low", truncated: false, filesBeyondLimit: 0, skippedFiles: 0 });
  });

  it("lists only the files at minConfidence or above, with a hint for the others", async () => {
    const medium = await scanUnreferencedFiles(spider, root, { minConfidence: "medium" });
    expect(medium.unreferencedFiles.map((file) => file.relativePath)).toEqual(["src/testOnly.ts"]);
    expect(medium.hint).toContain("low-confidence item(s) not listed");
    expect(medium.excluded).toBeUndefined();
  });

  it("scans a folder only, and reports maxFiles as a partial result", async () => {
    const folder = await scanUnreferencedFiles(spider, root, { scopePath: path.join(root, "src", "old") });
    expect(folder.unreferencedFiles.map((file) => file.relativePath)).toEqual(["src/old/index.ts"]);
    const capped = await scanUnreferencedFiles(spider, root, { maxFiles: 2 });
    expect(capped).toMatchObject({ scannedFiles: 2, truncated: true });
    expect(capped.filesBeyondLimit).toBeGreaterThan(0);
  });

  it("returns an empty list for a scope with no source file", async () => {
    const empty = await scanUnreferencedFiles(spider, root, { scopePath: path.join(root, "empty") });
    expect(empty).toMatchObject({ scannedFiles: 0, totalUnreferencedFiles: 0, unreferencedFiles: [], truncated: false });
  });

  it("rejects a scope outside the workspace", async () => {
    await expect(scanUnreferencedFiles(spider, root, { scopePath: path.dirname(root) })).rejects.toThrow();
  });

  it("stops when the signal aborts", async () => {
    await expect(scanUnreferencedFiles(spider, root, {}, AbortSignal.abort())).rejects.toThrow();
  });

  it("requires the reverse index", async () => {
    const noIndex = new SpiderBuilder().withRootDir(root).withReverseIndex(false).build();
    await expect(noIndex.scanUnreferencedFiles(root)).rejects.toMatchObject({ code: SpiderErrorCode.INDEX_NOT_READY });
  });
});

describe("scanUnreferencedFiles on the legacy-shop demo", { timeout: 60_000 }, () => {
  it("lists legacy/dailyReport.ts", async () => {
    const root = path.resolve(__dirname, "../../demo/legacy-shop");
    const spider = new SpiderBuilder().withRootDir(root).withReverseIndex(true).build();
    await spider.buildFullIndex();
    const result = await scanUnreferencedFiles(spider, root, {});
    expect(result.unreferencedFiles).toContainEqual(expect.objectContaining({ relativePath: "legacy/dailyReport.ts", exports: 1, reasons: ["no-importer"] }));
  });
});
